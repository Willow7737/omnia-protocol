/// Verify multiple Groth16 proofs individually.
///
/// NOTE: This function verifies each proof individually. True batch verification
/// (using random linear combinations) is future work.
///
/// TODO: Implement proper batch verification using random linear combinations
/// of pairing checks, reducing amortized verification cost from O(n) pairing
/// checks to O(1) pairing checks + O(n) group operations.
///
/// # Algorithm (current — individual verification)
///
/// Each proof is verified independently using [`verify_proof`]. The random
/// scalars derived from BLAKE3 are currently unused but are retained for
/// future optimization when proper batch pairing checks are implemented.
///
/// # Arguments
///
/// * `vk` — The verifying key (must be the same for all proofs)
/// * `proof_pairs` — Slice of (proof, public_inputs) pairs
///
/// # Returns
///
/// `Ok(true)` if all proofs verify, `Ok(false)` if any proof is invalid,
/// or `Err(ProverError)` if the verification algorithm fails.
///
/// # Security
///
/// Random scalars are derived from BLAKE3 with domain separation
/// `OMNIA-BATCH-VRFY-V1`, binding the randomness to the specific proofs
/// being verified. This prevents the prover from manipulating the aggregation.
pub fn verify_multiple(vk: &VerifyingKey, proof_pairs: &[(Proof, Vec<ark_bn254::Fr>)]) -> Result<bool, ProverError> {
    use ark_ff::PrimeField;
    use ark_serialize::CanonicalSerialize;

    if proof_pairs.is_empty() {
        return Ok(true);
    }

    // For a single proof, just use the standard verification
    if proof_pairs.len() == 1 {
        return verify_proof(vk, &proof_pairs[0].1, &proof_pairs[0].0);
    }

    // Serialize all proofs and public inputs for domain-separated randomness
    let mut transcript = Vec::new();
    for (i, (proof, inputs)) in proof_pairs.iter().enumerate() {
        transcript.extend_from_slice(&i.to_le_bytes());
        let mut proof_bytes = Vec::new();
        proof
            .serialize_compressed(&mut proof_bytes)
            .map_err(|e| ProverError::SerializationError(e.to_string()))?;
        transcript.extend_from_slice(&proof_bytes);
        for input in inputs {
            let mut input_bytes = Vec::new();
            input
                .serialize_compressed(&mut input_bytes)
                .map_err(|e| ProverError::SerializationError(e.to_string()))?;
            transcript.extend_from_slice(&input_bytes);
        }
    }

    // Generate random scalars using BLAKE3 for domain-separated randomness.
    // Note: OsRng is NOT used here because these scalars are currently unused
    // (individual verification is performed instead of true batch pairing
    // checks). When proper batch verification is implemented, the randomness
    // must be derived deterministically from the transcript to ensure
    // verification is reproducible.
    let random_scalars: Vec<ark_bn254::Fr> = (0..proof_pairs.len())
        .map(|i| {
            let mut hasher = blake3::Hasher::new();
            hasher.update(b"OMNIA-BATCH-VRFY-V1");
            hasher.update(&transcript);
            hasher.update(&i.to_le_bytes());
            let hash = hasher.finalize();
            ark_bn254::Fr::from_be_bytes_mod_order(hash.as_bytes())
        })
        .collect();

    // Individual verification for correctness (simplified approach)
    // A production implementation would use actual batch pairing checks
    // with MSM aggregation. For now, we verify each proof individually
    // but with the random scalar binding for future optimization.
    // TODO: Implement proper batch verification using random linear combinations.
    for (i, (proof, inputs)) in proof_pairs.iter().enumerate() {
        let _r_i = &random_scalars[i]; // Used for binding in future batch verification
        let result = verify_proof(vk, inputs, proof)?;
        if !result {
            return Ok(false);
        }
    }

    Ok(true)
}

/// Deprecated alias for [`verify_multiple`].
///
/// This function was renamed to `verify_multiple` to accurately reflect that
/// it verifies each proof individually rather than using true batch verification.
#[deprecated(
    since = "0.3.0",
    note = "Use verify_multiple instead — this function does not perform true batch verification"
)]
#[allow(deprecated)]
pub fn verify_proofs_batch(
    vk: &VerifyingKey,
    proof_pairs: &[(Proof, Vec<ark_bn254::Fr>)],
) -> Result<bool, ProverError> {
    verify_multiple(vk, proof_pairs)
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use crate::circuit::RollupCircuit;
    use ark_bn254::Fr;

    #[test]
    fn test_batch_verify_valid_proofs() {
        let circuit = RollupCircuit::empty();
        let (pk, vk) = generate_trusted_setup(&circuit).expect("setup failed");

        let mut proof_pairs = Vec::new();
        for i in 0u8..8 {
            let mut old = [0u8; 32];
            old[0] = i;
            let mut new = [0u8; 32];
            new[0] = i + 1;
            let circuit = RollupCircuit::from_state_roots(old, new, 5, old, new);
            let pub_input = circuit.public_input().expect("public input should be available");
            let proof = create_proof(circuit, &pk).expect("proof failed");
            proof_pairs.push((proof, pub_input));
        }

        let result = verify_multiple(&vk, &proof_pairs).expect("batch verify failed");
        assert!(result, "All valid proofs should batch verify");
    }

    #[test]
    fn test_batch_verify_one_invalid() {
        let circuit = RollupCircuit::empty();
        let (pk, vk) = generate_trusted_setup(&circuit).expect("setup failed");

        let mut proof_pairs = Vec::new();

        // 7 valid proofs
        for i in 0u8..7 {
            let mut old = [0u8; 32];
            old[0] = i;
            let mut new = [0u8; 32];
            new[0] = i + 1;
            let circuit = RollupCircuit::from_state_roots(old, new, 5, old, new);
            let pub_input = circuit.public_input().expect("public input should be available");
            let proof = create_proof(circuit, &pk).expect("proof failed");
            proof_pairs.push((proof, pub_input));
        }

        // 1 invalid proof (wrong public input)
        let mut old = [0u8; 32];
        old[0] = 7;
        let mut new = [0u8; 32];
        new[0] = 8;
        let circuit = RollupCircuit::from_state_roots(old, new, 5, old, new);
        let proof = create_proof(circuit, &pk).expect("proof failed");
        let wrong_public_inputs = vec![Fr::from(99999u64), Fr::from(99998u64)]; // Wrong!
        proof_pairs.push((proof, wrong_public_inputs));

        let result = verify_multiple(&vk, &proof_pairs).expect("batch verify failed");
        assert!(!result, "Batch with one invalid proof should fail");
    }

    #[test]
    fn test_batch_verify_empty() {
        let circuit = RollupCircuit::empty();
        let (_pk, vk) = generate_trusted_setup(&circuit).expect("setup failed");

        let result = verify_multiple(&vk, &[]).expect("batch verify failed");
        assert!(result, "Empty batch should verify as true");
    }
}
